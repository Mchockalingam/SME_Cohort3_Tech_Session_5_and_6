"""Demo 1: conversation memory in a real LangGraph, without an API key.

Run: python demo_01_thread_memory.py
The reply is a deterministic teaching simulation, NOT a language model.
LangGraph manages the state, message updates, threads, and checkpoints.
"""

# Message classes distinguish user input from assistant replies in the graph state.
from langchain_core.messages import AIMessage, HumanMessage
# In-memory checkpointing lets a graph resume a conversation while this process runs.
from langgraph.checkpoint.memory import InMemorySaver
# These building blocks define the graph's state, entry point, and end point.
from langgraph.graph import END, START, MessagesState, StateGraph


def find_operating_system(messages):
    """Read only user messages; the latest explicit OS mention wins."""
    # Search newest-to-oldest so the most recent explicit mention takes precedence.
    for message in reversed(messages):
        # Ignore assistant replies; only a user's own words count as an OS mention.
        if not isinstance(message, HumanMessage):
            continue
        # Normalize case so matching works regardless of capitalization.
        text = str(message.content).casefold()
        # Return the first supported OS found, which is the latest one in the history.
        if "windows 11" in text:
            return "Windows 11"
        if "ubuntu" in text:
            return "Ubuntu"
    # No supported operating system was explicitly mentioned by the user.
    return None


def assistant(state: MessagesState):
    """A node reads the assembled thread state and returns one new message."""
    # The last message is the latest input; normalize it for case-insensitive matching.
    latest_text = str(state["messages"][-1].content).casefold()
    # Search the whole conversation for the most recent OS mentioned by the user.
    operating_system = find_operating_system(state["messages"])
    # Answer the recall question using the OS found in the thread history, if any.
    if "which operating system" in latest_text:
        if operating_system:
            reply = f"You mentioned {operating_system}."
        else:
            reply = "I cannot find an operating system in this conversation."
    else:
        # For any other input, give the user a prompt for the supported question.
        reply = "Thanks. Ask me which operating system you mentioned."
    # MessagesState merges this update with history; return only the new assistant message.
    return {"messages": [AIMessage(content=reply)]}


def build_graph(checkpointer=None):
    """Build the same workflow with or without a checkpoint backend."""
    # Create a graph whose shared state is a list of conversation messages.
    builder = StateGraph(MessagesState)
    # Register the function that generates each assistant response.
    builder.add_node("assistant", assistant)
    # Route each invocation from the graph's start into the assistant node.
    builder.add_edge(START, "assistant")
    # Finish the invocation after the assistant has produced its response.
    builder.add_edge("assistant", END)
    # Compile the workflow; an optional checkpointer can persist state between turns.
    return builder.compile(checkpointer=checkpointer)


def show_turn(graph, text, config):
    # Submit only this turn's user message; the checkpointer restores earlier messages.
    result = graph.invoke({"messages": [HumanMessage(content=text)]}, config)
    # Display the user input and the latest assistant response.
    print(f"User: {text}")
    print(f"Simulated assistant: {result['messages'][-1].content}")
    # Show how many messages are present in the state returned by this invocation.
    print(f"Messages in returned state: {len(result['messages'])}")
    # Return the full state so the demo can verify the expected behavior.
    return result


def main():
    # Introduce the demo and clarify that responses are not generated by an LLM.
    print("DEMO 1 | Real LangGraph memory; simulated replies; no LLM calls.\n")
    # A thread ID identifies a conversation when a checkpointer is enabled.
    same_thread = {"configurable": {"thread_id": "it-support-session-a"}}
    # A second ID represents an independent conversation with its own history.
    new_thread = {"configurable": {"thread_id": "it-support-session-b"}}
    # Prepare a fact to remember and a later question that asks the graph to recall it.
    statement = "I use Windows 11."
    question = "Which operating system did I mention?"

    # First demonstrate that a thread ID without a checkpointer does not save state.
    print("A. No checkpointer: a thread ID alone does not retain history.")
    stateless = build_graph()
    show_turn(stateless, statement, same_thread)  # This invocation knows only the statement.
    forgotten = show_turn(stateless, question, same_thread)  # Prior state is not restored.
    # The response should not recall Windows 11 because the earlier turn was not saved.
    assert "Windows 11" not in forgotten["messages"][-1].content
    # This result contains just the current user question and its assistant response.
    assert len(forgotten["messages"]) == 2

    # Now enable an in-memory saver to restore the prior state for the same thread.
    print("\nB. InMemorySaver: the same thread resumes its conversation.")
    graph = build_graph(checkpointer=InMemorySaver())
    show_turn(graph, statement, same_thread)  # The saver records this turn's messages.
    remembered = show_turn(graph, question, same_thread)  # The saver restores the history.
    # The assistant can now find the user's earlier Windows 11 statement.
    assert "Windows 11" in remembered["messages"][-1].content
    # The state includes two user messages and two assistant responses.
    assert len(remembered["messages"]) == 4

    # Confirm that a separate thread starts with no history from the first thread.
    print("\nC. A different thread starts with a separate conversation.")
    separate = show_turn(graph, question, new_thread)
    # The new thread has no OS statement to recall.
    assert "Windows 11" not in separate["messages"][-1].content
    # Its state contains only this question and its response.
    assert len(separate["messages"]) == 2

    # Read the saved snapshot for the original thread and list the message roles.
    snapshot = graph.get_state(same_thread)
    roles = ", ".join(message.type for message in snapshot.values["messages"])
    print(f"\nOriginal thread still contains 4 messages: [{roles}]")
    # Verify that running the other thread did not change the original thread's history.
    assert len(snapshot.values["messages"]) == 4
    print("PASS: no memory without a saver; same-thread recall; thread separation.")
    # InMemorySaver is process-local, so its checkpoint data disappears when Python exits.
    print("InMemorySaver lives in RAM. Its data is lost when this process ends.")
    # In a real app, authorize a user before allowing access to a thread ID's data.
    print("Thread IDs select records; a real app must also authorize access.")


# Run the demo only when this file is executed directly, not when imported as a module.
if __name__ == "__main__":
    main()
